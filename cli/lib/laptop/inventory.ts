// The Ansible inventory `forge install` generates for a host, in the shape of
// ansible/inventory.lima.example.yml and ansible/inventory.example.yml.
import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import { shellQuote } from "../shell.ts";
import type { LaptopHost } from "./state.ts";

// Same alias as the Lima wait (lima.ts), which stores the VM's key under it.
const HOST_KEY_ALIAS = "forge-local-admin";

// Every string is a YAML double-quoted scalar: JSON is valid YAML.
const q = (s: string): string => JSON.stringify(s);

export function renderInventory(
  h: LaptopHost,
  o: { forgeKey: string; adminKeyFile: string; knownHosts: string },
): string {
  // Ansible splits ansible_ssh_common_args with shlex: a value that is a path
  // or a socket is single-quoted so that a space in it survives.
  const args = ["-o IdentitiesOnly=yes", `-o UserKnownHostsFile=${shellQuote(o.knownHosts)}`];
  if (h.kind === "lima") args.push(`-o HostKeyAlias=${HOST_KEY_ALIAS}`, "-o StrictHostKeyChecking=accept-new");
  if (h.identityAgent) args.push(`-o IdentityAgent=${shellQuote(h.identityAgent)}`);
  // No ansible_port for a remote host: an explicit one would stop the preflight
  // from probing forge_ssh_port, locking out a developer who edits it. Lima
  // forwards a local port to sshd, which stays on 22: it needs ansible_port.
  const port = h.kind === "lima" ? [`      ansible_port: ${h.port}`] : [];
  return [
    "---",
    "# Generated by `forge install`. It is written once: your edits are kept on",
    "# re-runs. ssh_keys is authoritative: keys added by hand to the user's",
    "# authorized_keys are removed on the next run.",
    "all:",
    "  hosts:",
    `    ${h.name}:`,
    `      ansible_host: ${q(h.address)}`,
    ...port,
    `      ansible_user: ${q(h.admin)}`,
    `      ansible_ssh_private_key_file: ${q(o.adminKeyFile)}`,
    `      ansible_ssh_common_args: ${q(args.join(" "))}`,
    "  vars:",
    `    forge_exposure: ${q(h.exposure)}`,
    "    forge_users:",
    `      - name: ${q(h.user)}`,
    "        ssh_keys:",
    `          - ${q(o.forgeKey)}`,
    "",
  ].join("\n");
}

// An existing inventory is never overwritten.
export function writeInventoryOnce(path: string, text: string): "written" | "kept" {
  if (existsSync(path)) return "kept";
  mkdirSync(dirname(path), { recursive: true, mode: 0o700 });
  writeFileSync(path, text, { mode: 0o600, flag: "wx" });
  return "written";
}
